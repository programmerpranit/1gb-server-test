-- Shared schema for every implementation (apps/*). Do not change per-app;
-- schema/index changes are their own tagged experiment.
-- Loaded by scripts/seed_db.sh into the `bench_seed` template database.

CREATE TABLE locations (
    id          integer PRIMARY KEY,
    country     text,
    state       text,
    state_code  text,
    city        text
);

CREATE TABLE users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle      text NOT NULL UNIQUE,          -- original "tw-<id>" from the dataset
    gender      text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE posts (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- monotonic with time
    external_id    bigint UNIQUE,                 -- original tweet id (NULL for posts created by the API)
    user_id        bigint NOT NULL REFERENCES users(id),
    location_id    integer REFERENCES locations(id),
    text           text NOT NULL,
    lang           text,
    is_public      boolean NOT NULL DEFAULT true,
    is_reshare     boolean NOT NULL DEFAULT false,
    reach          integer,
    retweet_count  integer,
    like_count     integer NOT NULL DEFAULT 0,
    comment_count  integer NOT NULL DEFAULT 0,
    klout          integer,
    sentiment      real,
    created_at     timestamptz NOT NULL DEFAULT now()
);

-- Global feed: WHERE is_public AND id < $before ORDER BY id DESC LIMIT n
CREATE INDEX posts_public_feed_idx ON posts (id DESC) WHERE is_public;
-- User feed / my posts: WHERE user_id = $1 AND id < $before ORDER BY id DESC LIMIT n
CREATE INDEX posts_user_feed_idx ON posts (user_id, id DESC);

CREATE TABLE likes (
    post_id     bigint NOT NULL REFERENCES posts(id),
    user_id     bigint NOT NULL REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id, user_id)
);

CREATE TABLE comments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     bigint NOT NULL REFERENCES posts(id),
    user_id     bigint NOT NULL REFERENCES users(id),
    text        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX comments_post_idx ON comments (post_id, id DESC);
